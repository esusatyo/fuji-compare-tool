function withBlock(html, block, file, begin, end) {
  const start = html.indexOf(begin);
  const stop = html.indexOf(end);
  if (start === -1 || stop === -1) {
    throw new Error(`${file}: ${begin} / ${end} markers not found — refusing to write`);
  }
  return html.slice(0, start) + block + html.slice(stop + end.length);
}

function withHeadBlock(html, block, file) {
  return withBlock(html, block, file, SEO_BEGIN, SEO_END);
}

