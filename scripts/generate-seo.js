function productLd(brandName, cam) {
  const p = { '@type': 'Product', name: `${brandName} ${cam.name}`, brand: { '@type': 'Brand', name: brandName } };
  if (cam.imageUrl) p.image = cam.imageUrl;
  if (cam.prices && cam.prices.USD != null) {
    p.offers = { '@type': 'Offer', priceCurrency: 'USD', price: cam.prices.USD };
  }
  return p;
}

// Other curated pairs that share a camera with (aId, bId), so vs-pages form a
// connected cluster rather than isolated leaves. Deterministic: newest pair
// first, then priciest, then slug — capped so link equity stays focused.
function relatedPairs(allPairs, cams, aId, bId) {
  const self = `${aId}|${bId}`;
  const usd = id => (cams[id] && cams[id].prices && cams[id].prices.USD) || 0;
  const yr = id => (cams[id] && cams[id].year) || 0;
  return allPairs
    .filter(([x, y]) => `${x}|${y}` !== self && (x === aId || x === bId || y === aId || y === bId))
    .sort((p, q) => {
      const pn = Math.max(yr(p[0]), yr(p[1])), qn = Math.max(yr(q[0]), yr(q[1]));
      if (pn !== qn) return qn - pn;
      const pu = Math.max(usd(p[0]), usd(p[1])), qu = Math.max(usd(q[0]), usd(q[1]));
      if (pu !== qu) return qu - pu;
      return `${p[0]}|${p[1]}` < `${q[0]}|${q[1]}` ? -1 : 1;
    })
    .slice(0, 6);
}

function vsPageHTML(brand, data, site, aId, bId, allPairs) {
  const cams = data.CAMERAS;
  const brandName = data.BRAND_CONFIG.name;
  const [a, b] = [cams[aId], cams[bId]];
  const title = `${brandName} ${a.name} vs ${b.name}: Spec Comparison`;
  const desc = `Compare the ${brandName} ${a.name} (${a.year}) and ${b.name} (${b.year}) side by side — price, sensor, stabilization, video, weight and more.`;
  const url = `${site.baseUrl}/${brand}/vs/${aId}-vs-${bId}.html`;
  const ld = {
    '@context': 'https://schema.org',
    '@type': 'ItemList',
    name: title,
    itemListElement: [a, b].map((c, i) => ({ '@type': 'ListItem', position: i + 1, item: productLd(brandName, c) })),
  };
  const rows = VS_ROWS.map(([label, fn]) => {
    const [va, vb] = [fn(a), fn(b)];
    return `      <tr><th scope="row">${esc(label)}</th><td>${va == null ? '—' : esc(va)}</td><td>${vb == null ? '—' : esc(vb)}</td></tr>`;
  }).join('\n');

  const related = relatedPairs(allPairs || [], cams, aId, bId);
  const relatedHTML = related.length ? `
  <h2>Related comparisons</h2>
  <ul class="related">
${related.map(([x, y]) =>
    `    <li><a href="${x}-vs-${y}.html">${esc(brandName)} ${esc(cams[x].name)} vs ${esc(cams[y].name)}</a></li>`).join('\n')}
  </ul>` : '';

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(desc)}">
  <link rel="canonical" href="${url}">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="${esc(site.siteName)}">
  <meta property="og:title" content="${esc(title)}">
  <meta property="og:description" content="${esc(desc)}">
  <meta property="og:url" content="${url}">
  <meta name="twitter:card" content="summary">
  <script type="application/ld+json">${JSON.stringify(ld)}</script>
  <!-- Umami analytics — temporarily disabled, kept for re-enabling.
  <script defer src="https://cloud.umami.is/script.js" data-website-id="365e9ee6-1fb5-4a0d-9c74-f6255522a196"></script> -->
  <script data-goatcounter="https://esusatyo.goatcounter.com/count" defer src="https://gc.zgo.at/count.js"></script>
  <style>${VS_CSS}</style>
</head>
<body>
  <h1>${esc(brandName)} ${esc(a.name)} vs ${esc(b.name)}</h1>
  <p>The ${esc(brandName)} <strong>${esc(a.name)}</strong> (${a.year}) and <strong>${esc(b.name)}</strong> (${b.year}) compared side by side.
     Key specifications are below; the interactive tool adds the full spec sheet, winner highlighting,
     seven currencies and a third comparison slot.</p>
  <a class="cta" href="../index.html#cameras=${aId},${bId}">Open this comparison in the interactive tool &rarr;</a>
  <table>
    <thead>
      <tr><th scope="col">Spec</th><th scope="col">${esc(a.name)}</th><th scope="col">${esc(b.name)}</th></tr>
    </thead>
    <tbody>
${rows}
    </tbody>
  </table>
  <p>Prices shown are approximate manufacturer list prices (RRP) in USD and may differ from live retail prices.</p>${relatedHTML}
  <footer>
    <a href="../index.html">All ${esc(brandName)} cameras &amp; lenses</a> &middot;
    <a href="../../about.html">About</a> &middot;
    <a href="../../privacy.html">Privacy</a><br>
    Specs &amp; prices last verified: ${esc(site.dataVerified)}
  </footer>
</body>
</html>
`;
}

// ─── Head blocks ─────────────────────────────
function metaBlock(site, url, title, desc) {
  return `${SEO_BEGIN}
  <meta name="description" content="${esc(desc)}">
  <link rel="canonical" href="${url}">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="${esc(site.siteName)}">
  <meta property="og:title" content="${esc(title)}">
  <meta property="og:description" content="${esc(desc)}">
  <meta property="og:url" content="${url}">
  <meta name="twitter:card" content="summary">
  ${SEO_END}`;
}

function brandHeadBlock(brand, data, site) {
  const name = data.BRAND_CONFIG.name;
  const nCams = Object.keys(data.CAMERAS).length;
  const nLenses = Object.keys(data.LENSES).length;
  return metaBlock(
    site,
    `${site.baseUrl}/${brand}/`,
    `${name} Camera & Lens Comparison`,
    `Compare ${nCams} ${name} cameras and ${nLenses} lenses side by side — price, sensor, autofocus, stabilization and video, in 7 currencies.`
  );
}

function rootHeadBlock(site, brandNames) {
  return metaBlock(
    site,
    `${site.baseUrl}/`,
    `${site.siteName} — Camera & Lens Comparison`,
    `Side-by-side camera and lens comparison for ${brandNames.join(', ')} — specs, prices and buy links in 7 currencies.`
  );
}

// Replace the content between a begin/end marker pair, preserving everything
// outside it. Refuses to write when either marker is missing, so a page that
// lost its markers fails loudly instead of silently dropping generated content.
// Crawlable block appended to each brand page, below the interactive tool.
// Links every curated vs-page for the brand, so no vs-page is orphaned: each
// is reachable from its brand page even before cross-linking.
function brandBodyBlock(brand, data, site, pairs) {
  const name = data.BRAND_CONFIG.name;
  const cams = data.CAMERAS;
  const nCams = Object.keys(cams).length;
  const nLenses = Object.keys(data.LENSES).length;
  const items = pairs.map(([a, b]) =>
    `      <li><a href="vs/${a}-vs-${b}.html">${esc(name)} ${esc(cams[a].name)} vs ${esc(cams[b].name)}</a></li>`
  ).join('\n');
  return `${SEO_BODY_BEGIN}
  <section class="seo-links" aria-label="Popular ${esc(name)} comparisons">
    <h2>Popular ${esc(name)} camera comparisons</h2>
    <p>Compare all ${nCams} ${esc(name)} cameras and ${nLenses} lenses side by side — price, sensor, autofocus, stabilization and video, in seven currencies. Popular head-to-head comparisons:</p>
    <ul>
${items}
    </ul>
  </section>
  ${SEO_BODY_END}`;
}

// Crawlable landing content for the root page: brand cards with live counts
// plus a sample of vs-pages, so the root passes authority into the cluster.
function rootBodyBlock(site, brands) {
  const cards = brands.map(br =>
    `      <li class="brand-card"><a href="./${br.slug}/"><strong>${esc(br.name)}</strong></a> <span>${br.nCams} cameras · ${br.nLenses} lenses</span></li>`
  ).join('\n');
  const cluster = brands.flatMap(br =>
    br.samplePairs.map(p =>
      `      <li><a href="./${br.slug}/vs/${p.a}-vs-${p.b}.html">${esc(br.name)} ${esc(p.aName)} vs ${esc(p.bName)}</a></li>`)
  ).join('\n');
  return `${SEO_BODY_BEGIN}
  <main class="landing">
    <h1>${esc(site.siteName)}</h1>
    <p>Side-by-side camera and lens comparisons for ${brands.map(b => esc(b.name)).join(', ')} — specs, prices and buy links in seven currencies. Pick a brand to start comparing.</p>
    <ul class="brand-grid">
${cards}
    </ul>
    <h2>Popular comparisons</h2>
    <ul class="cluster">
${cluster}
    </ul>
  </main>
  ${SEO_BODY_END}`;
}

function withBlock(html, block, file, begin, end) {
  const start = html.indexOf(begin);
  const stop = html.indexOf(end);
  if (start === -1 || stop === -1) {
    throw new Error(`${file}: ${begin} / ${end} markers not found — refusing to write`);
  }
  return html.slice(0, start) + block + html.slice(stop + end.length);
}

function withHeadBlock(html, block, file) {
  return withBlock(html, block, file, SEO_BEGIN, SEO_END);
}

function withBodyBlock(html, block, file) {
  return withBlock(html, block, file, SEO_BODY_BEGIN, SEO_BODY_END);
}

// ─── Sitemap & robots ────────────────────────
function sitemapXML(site, paths) {
  const urls = paths.map(p => `  <url><loc>${site.baseUrl}/${p}</loc></url>`).join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url><loc>${site.baseUrl}/</loc></url>
${urls}
</urlset>
`;
}

function robotsTxt(site) {
  return `User-agent: *
Allow: /

Sitemap: ${site.baseUrl}/sitemap.xml
`;
}

// ─── Build everything (pure — returns path → content) ───
function buildAll() {
  const site = siteConfig();
  const files = new Map();
  const sitemapPaths = [];
  const brandNames = [];
  const brandInfo = [];

  for (const brand of brandDirs()) {
    const { data } = loadBrand(brand);
    const name = data.BRAND_CONFIG.name;
    brandNames.push(name);

    const pairs = curatedPairs(data.CAMERAS);

    const idx = path.join(brand, 'index.html');
    let idxHtml = fs.readFileSync(path.join(ROOT, idx), 'utf8');
    idxHtml = withHeadBlock(idxHtml, brandHeadBlock(brand, data, site), idx);
    idxHtml = withBodyBlock(idxHtml, brandBodyBlock(brand, data, site, pairs), idx);
    files.set(idx, idxHtml);
    sitemapPaths.push(`${brand}/`);

    for (const [a, b] of pairs) {
      const rel = `${brand}/vs/${a}-vs-${b}.html`;
      files.set(rel, vsPageHTML(brand, data, site, a, b, pairs));
      sitemapPaths.push(rel);
    }

    const cams = data.CAMERAS;
    brandInfo.push({
      slug: brand,
      name,
      nCams: Object.keys(cams).length,
      nLenses: Object.keys(data.LENSES).length,
      samplePairs: pairs.slice(0, 3).map(([a, b]) => ({ a, b, aName: cams[a].name, bName: cams[b].name })),
    });
  }

  sitemapPaths.push('about.html', 'privacy.html');
  let rootHtml = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  rootHtml = withHeadBlock(rootHtml, rootHeadBlock(site, brandNames), 'index.html');
  rootHtml = withBodyBlock(rootHtml, rootBodyBlock(site, brandInfo), 'index.html');
  files.set('index.html', rootHtml);
  files.set('sitemap.xml', sitemapXML(site, sitemapPaths));
  files.set('robots.txt', robotsTxt(site));
  return files;
}

// ─── CLI ─────────────────────────────────────
if (require.main === module) {
  const files = buildAll();
  let written = 0;
  for (const [rel, content] of files) {
    const abs = path.join(ROOT, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    if (!fs.existsSync(abs) || fs.readFileSync(abs, 'utf8') !== content) {
      fs.writeFileSync(abs, content);
      written++;
    }
  }
  // Remove stale vs-pages no longer in the curated set.
  let removed = 0;
  for (const brand of brandDirs()) {
    const vsDir = path.join(ROOT, brand, 'vs');
    if (!fs.existsSync(vsDir)) continue;
    for (const f of fs.readdirSync(vsDir)) {
      if (!files.has(`${brand}/vs/${f}`)) { fs.unlinkSync(path.join(vsDir, f)); removed++; }
    }
  }
  console.log(`generate-seo: ${files.size} artifacts (${written} written, ${removed} stale removed)`);
}

module.exports = { siteConfig, curatedPairs, relatedPairs, vsPageHTML, brandHeadBlock, rootHeadBlock, brandBodyBlock, rootBodyBlock, withHeadBlock, withBodyBlock, sitemapXML, robotsTxt, buildAll, SEO_BEGIN, SEO_END, SEO_BODY_BEGIN, SEO_BODY_END };
