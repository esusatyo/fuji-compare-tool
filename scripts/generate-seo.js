// Other curated pairs that share a camera with (aId, bId), so vs-pages form a
// connected cluster rather than isolated leaves. Deterministic: newest pair
// first, then priciest, then slug — capped so link equity stays focused.
function relatedPairs(allPairs, cams, aId, bId) {
  const self = `${aId}|${bId}`;
  const usd = id => (cams[id] && cams[id].prices && cams[id].prices.USD) || 0;
  const yr = id => (cams[id] && cams[id].year) || 0;
  return allPairs
    .filter(([x, y]) => `${x}|${y}` !== self && (x === aId || x === bId || y === aId || y === bId))
    .sort((p, q) => {
      const pn = Math.max(yr(p[0]), yr(p[1])), qn = Math.max(yr(q[0]), yr(q[1]));
      if (pn !== qn) return qn - pn;
      const pu = Math.max(usd(p[0]), usd(p[1])), qu = Math.max(usd(q[0]), usd(q[1]));
      if (pu !== qu) return qu - pu;
      return `${p[0]}|${p[1]}` < `${q[0]}|${q[1]}` ? -1 : 1;
    })
    .slice(0, 6);
}

// Static vs-pages default to the USD marketplace (amazon.com); the interactive
// tool offers all seven currencies. ASIN → the product page, else a search that
// always resolves. Mirrors engine.js amazonBuyUrl (no affiliate tag yet).
function amazonBuyUrlUSD(brandName, cam) {
  if (cam.asin) return `https://www.amazon.com/dp/${cam.asin}`;
  return `https://www.amazon.com/s?k=${encodeURIComponent(`${brandName} ${cam.name}`)}`;
}

