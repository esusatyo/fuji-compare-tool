function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

// Cloudflare Workers static assets 307-redirects `/page.html` to the
// extensionless `/page` (html_handling: auto-trailing-slash, the
// default). Canonicals, og:urls, sitemap entries AND internal <a href>s
// must therefore all use the clean URL. Canonicals alone are not enough:
// Google discovers pages by following links, so .html hrefs put a
// *temporary* (307) redirect on every crawl path, which doesn't
// consolidate signals like a 301 and contradicts the clean canonical the
// destination then declares. Files on disk keep their .html names — only
// the URLs we publish are clean.
//
// Cost of that choice: extensionless URLs need a host that maps `/page`
// to `page.html`. Cloudflare Pages does; `python3 -m http.server` does
// not, so local preview goes through scripts/preview.py (see CLAUDE.md).
function cleanUrl(p) {
  return p.replace(/\.html$/, '');
}

// Same mapping for a relative href: `vs/a-vs-b.html` → `vs/a-vs-b`, and
// `../index.html` → `../` (a directory URL, which every host resolves to
// its index without a redirect).
function cleanHref(p) {
  const clean = p.replace(/(^|\/)index\.html$/, '$1').replace(/\.html$/, '');
  return clean === '' ? './' : clean;
}

// ─── Pairing rules ───────────────────────────
// The data's `series` field is a broad family (e.g. Sony "Alpha
// (Full-frame)" spans a7/a7R/a9/a1), so successor detection derives the
// *model line* from the slug structure instead.
const ROMAN = { i: 1, ii: 2, iii: 3, iv: 4, v: 5, vi: 6, vii: 7, viii: 8, ix: 9, x: 10 };

// Scheme A — roman-numeral generations of one line:
// a7r-v → a7r gen 5; x100vi → x100 gen 6; eos-r5-ii → eos-r5 gen 2.
function romanLine(slug) {
  let m = slug.match(/^(.+)-([ivx]+)$/);
  if (m && ROMAN[m[2]]) return { line: m[1], gen: ROMAN[m[2]] };
  m = slug.match(/^(.+\d)([ivx]+)$/);
  if (m && ROMAN[m[2]]) return { line: m[1], gen: ROMAN[m[2]] };
  return { line: slug, gen: 1 };
}

// Scheme B — numbered generations: x-t5 → line "x-t"/1-digit, gen 5.
// The digit count separates product tiers that share a stem
// (x-t5 flagship vs x-t50 mid-range vs x-t200 entry).
function numberLine(slug) {
  const m = slug.match(/^(.+?)(\d+)$/);
  return m ? { line: `${m[1]}#${m[2].length}`, gen: parseInt(m[2], 10) } : null;
}

function curatedPairs(cams) {
  const seen = new Set();
  const pairs = [];
  const usd = id => (cams[id].prices && cams[id].prices.USD) || 0;
  // Canonical order within a pair: newer first, then pricier, then slug.
  const add = (a, b) => {
    if (a === b) return;
    const [ca, cb] = [cams[a], cams[b]];
    if (cb.year > ca.year || (cb.year === ca.year && usd(b) > usd(a)) ||
        (cb.year === ca.year && usd(b) === usd(a) && b < a)) [a, b] = [b, a];
    const key = `${a}|${b}`;
    if (!seen.has(key)) { seen.add(key); pairs.push([a, b]); }
  };
  // Successors launch near their predecessor's RRP; a big gap means the
  // "line" grouping actually caught two different tiers (Z9 vs Z5).
  const priceClose = (a, b) =>
    usd(a) > 0 && usd(b) > 0 && Math.abs(usd(a) - usd(b)) / Math.max(usd(a), usd(b)) <= 0.4;

  // Rule 1: consecutive generations within a model line, newer body
  // still current. Scheme A is structurally unambiguous; scheme B adds
  // the price gate because a shared stem can still span tiers.
  const addSuccessors = (grouper, gated) => {
    const lines = {};
    for (const id of Object.keys(cams)) {
      const r = grouper(id);
      if (r) (lines[r.line] ??= []).push([id, r.gen]);
    }
    for (const list of Object.values(lines)) {
      list.sort((p, q) => q[1] - p[1] || cams[q[0]].year - cams[p[0]].year);
      for (let i = 0; i + 1 < list.length; i++) {
        const [newer, older] = [list[i][0], list[i + 1][0]];
        if (cams[newer].discontinued) continue;
        if (gated && !priceClose(newer, older)) continue;
        add(newer, older);
      }
    }
  };
  addSuccessors(romanLine, false);
  addSuccessors(numberLine, true);

  // Rule 2: current bodies vs their two nearest USD-price neighbours.
  const current = Object.keys(cams)
    .filter(id => !cams[id].discontinued && usd(id) > 0)
    .sort((a, b) => usd(b) - usd(a) || (a < b ? -1 : 1));
  for (let i = 0; i < current.length; i++) {
    for (let k = 1; k <= 2 && i + k < current.length; k++) add(current[i], current[i + k]);
  }
  return pairs;
}

